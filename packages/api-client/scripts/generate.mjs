// Generates the TypeScript types of each backend API from its OpenAPI document.
//
//   pnpm generate:api                 from the snapshots in openapi/
//   pnpm generate:api --from-api      fetches each document from the running APIs first (the Docker ports below,
//                                     or DLM_<APP>_API_URL) and refreshes the snapshot
//
// The API writes whole numbers as "integer or numeric string" (it accepts both); the front end always sends and reads
// numbers, so those become plain numbers. The platform types (sign-in, masters, people, administration) are the same
// in every API and are written once, from the DCR document.
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const apps = {
  dcr: { port: 5555, title: 'Document Change Request' },
  dn: { port: 7777, title: 'Deviation Note' },
  cc: { port: 2222, title: 'Customer Complaint' },
  ecn: { port: 8888, title: 'Engineering Change Note and TCN' },
  mppl: { port: 9999, title: 'MPPL Escalation Tracker' },
};
const platformPath =
  /^\/api\/v1\/(me|system\/|directory\/|masters)|^\/api\/v1\/admin\/(jobs|audit|emails|logs|permissions|roles|sequences|users|masters)/;

const fromApi = process.argv.includes('--from-api');

function normalise(node) {
  if (Array.isArray(node)) return node.map(normalise);
  if (node === null || typeof node !== 'object') return node;
  const copy = Object.fromEntries(Object.entries(node).map(([key, value]) => [key, normalise(value)]));
  if (Array.isArray(copy.type) && copy.type.includes('string') && (copy.type.includes('integer') || copy.type.includes('number'))) {
    copy.type = copy.type.filter((t) => t !== 'string');
    if (copy.type.length === 1) copy.type = copy.type[0];
    delete copy.pattern;
  }
  return copy;
}

async function load(app) {
  const file = join(root, 'openapi', `${app}.json`);
  if (fromApi) {
    const base = process.env[`DLM_${app.toUpperCase()}_API_URL`] ?? `http://localhost:${apps[app].port}`;
    const response = await fetch(`${base}/openapi/v1.json`);
    if (!response.ok) throw new Error(`${base}/openapi/v1.json answered ${response.status}`);
    await writeFile(file, JSON.stringify(await response.json(), null, 2) + '\n');
  }
  return normalise(JSON.parse(await readFile(file, 'utf8')));
}

async function write(name, document, description) {
  const ast = await openapiTS(document, { rootTypes: true, rootTypesNoSchemaPrefix: true, alphabetize: true });
  const header = `// Generated by scripts/generate.mjs from ${description}. Do not edit; run \`pnpm generate:api\`.\n\n`;
  await writeFile(join(root, 'src', 'generated', `${name}.ts`), header + astToString(ast));
  console.log(`src/generated/${name}.ts`);
}

await mkdir(join(root, 'src', 'generated'), { recursive: true });
const documents = {};
for (const app of Object.keys(apps)) {
  documents[app] = await load(app);
  await write(app, documents[app], `the ${apps[app].title} API (openapi/${app}.json)`);
}

const dcr = documents.dcr;
const platform = {
  ...dcr,
  info: { ...dcr.info, title: 'Cyient DLM platform endpoints' },
  paths: Object.fromEntries(Object.entries(dcr.paths).filter(([path]) => platformPath.test(path))),
};
await write('platform', platform, 'the platform endpoints every API shares (openapi/dcr.json)');
